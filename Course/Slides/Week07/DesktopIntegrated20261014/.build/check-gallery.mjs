import {chromium} from 'playwright';
import {pathToFileURL} from 'node:url';
import path from 'node:path';
import fs from 'node:fs';
const browser=await chromium.launch({headless:true,channel:'msedge'});
const page=await browser.newPage({viewport:{width:1440,height:900}});
await page.goto(pathToFileURL(path.resolve('../index.html')).href);
await page.locator('img').evaluateAll(imgs=>imgs.forEach(i=>i.loading='eager'));
await page.waitForFunction(()=>[...document.images].every(i=>i.complete));
const result=await page.evaluate(()=>({slides:document.querySelectorAll('article').length,brokenImages:[...document.images].filter(i=>!i.naturalWidth).map(i=>i.src),overflow:document.documentElement.scrollWidth>innerWidth}));
await page.selectOption('#filter','changed');
result.changedVisible=await page.locator('article:visible').count();
await page.selectOption('#filter','live');
result.liveVisible=await page.locator('article:visible').count();
await page.setViewportSize({width:760,height:900});
result.mobileOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
await browser.close();
fs.writeFileSync('gallery-check.json',JSON.stringify(result,null,2));
console.log(result);
if(result.brokenImages.length||result.overflow||result.mobileOverflow||result.slides!==134||result.liveVisible!==68)process.exitCode=1;
